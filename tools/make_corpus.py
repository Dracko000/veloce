#!/usr/bin/env python3
"""Build data/corpus.txt from this repository's own documentation.

Why this file exists: the byte-level bigram / native-trainer demos need a text
corpus, and the previous corpus was a scrape of unrelated local project notes --
it carried material that has no business in a public repository. Generating the
corpus from Veloce's own public docs keeps the demo reproducible, keeps the
provenance obvious, and means nothing enters the tree that is not already
published here.

Usage: python3 tools/make_corpus.py   (writes data/corpus.txt)
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

SOURCES = [
    "README.md",
    "PRD.md",
    "ERD.md",
    "docs/language.md",
    "docs/implementation-status.md",
    "docs/model-capabilities.md",
    "docs/training-framework.md",
    "models/veloce-1b/README.md",
]

HEADER = "Veloce documentation corpus (generated by tools/make_corpus.py).\n\n"


def main() -> None:
    parts = [HEADER]
    for rel in SOURCES:
        parts.append(f"===== {rel} =====\n")
        parts.append((ROOT / rel).read_text(encoding="utf-8"))
        parts.append("\n")
    out = ROOT / "data" / "corpus.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "".join(parts)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {len(text)} bytes from {len(SOURCES)} files")


if __name__ == "__main__":
    main()
