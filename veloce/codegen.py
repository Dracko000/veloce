"""C11 code generation for Veloce.

Lowers the type-checked, memory-planned AST to portable C11.  The generated
translation unit is compiled with ``-O3 -march=native`` and links against a
small hand-written runtime (``runtime/veloce_runtime.h``) that provides the
static arena, bit-packed trit access, and the MMIO / argument helpers.

Design notes
------------
* All *activations* are ``float`` (f32).  ``trit`` / ``fp16`` are storage
  dtypes: trit weights are bit-packed 5-per-byte and expanded at load time;
  fp16 weights live in buffers of ``uint16_t`` decoded on the fly.
* Every tensor value is represented as a pointer into the function's static
  arena (``float *`` for activations, ``int8_t *``/``uint16_t *`` for storage).
* Matmul with a trit weight lowers to integer add/sub over a decoded
  {-1,0,1} buffer (FR-1.3).  Matmul with float weights is a plain kernel.
"""

from . import ast
from .typecheck import TupleType

RUNTIME_INCLUDE = "veloce_runtime.h"

DTYPE_CTYPE = {
    "trit": "uint8_t",    # PACKED base-3 trits, 5 per byte (zero-copy weights)
    "fp16": "uint16_t",   # half-precision storage
    "f32": "float",
    "fp32": "float",
    "i32": "int32_t",
    "i64": "int64_t",
    "i8": "int8_t",
    "u8": "uint8_t",
    "i2": "uint8_t",   # PACKED signed 2-bit values, 4 per byte
    "fp8": "uint8_t",  # E4M3, one byte per value
    "i4": "uint8_t",   # PACKED signed nibbles, 2 per byte
    "bool": "bool",
}


def ctype_of(t):
    """C type used to *store* a value of Veloce type ``t``."""
    if isinstance(t, ast.TensorType):
        return DTYPE_CTYPE.get(t.dtype.name, "float") + " *"
    if isinstance(t, ast.ScalarType):
        return DTYPE_CTYPE.get(t.name, "float")
    return "double"


def is_tensor(t):
    return isinstance(t, ast.TensorType)


def numel(t):
    n = t.numel()
    if n is None:
        raise ValueError(f"unresolved shape {t}")
    return n


class CodeGen:
    def __init__(self, module, plans, diag):
        self.module = module
        self.plans = plans
        self.diag = diag
        self.lines = []
        self.indent = 0
        self.tmp_counter = 0
        self.weight_buffers = []  # (name, dims, dtype)
        self.fn = None

    # ---- emit helpers ---------------------------------------------------
    def emit(self, s=""):
        self.lines.append("    " * self.indent + s)

    def fresh(self, base="t"):
        self.tmp_counter += 1
        return f"__{base}{self.tmp_counter}"

    # ---- module ---------------------------------------------------------
    def generate(self):
        self.emit("/* Generated by Veloce AOT compiler. Do not edit. */")
        self.emit('#include "veloce_runtime.h"')
        self.emit("")
        # Forward declarations
        for fn in self.module.functions:
            self.emit(self.signature(fn) + ";")
        self.emit("")
        # Weight declarations (extern, defined in the loader-provided .c/.bin)
        for fn in self.module.functions:
            if fn.is_extern:
                continue
            self.declare_weights(fn)
        self.emit("")
        for fn in self.module.functions:
            if fn.is_extern:
                continue
            self.gen_function(fn)
        return "\n".join(self.lines) + "\n"

    def signature(self, fn):
        rets = fn.ret_types
        params = []
        for p in fn.params:
            params.append(f"{ctype_of(p.type)} {p.cname}")
        if len(rets) > 1:
            for i, r in enumerate(rets):
                params.append(f"{ctype_of(r)} *__out{i}")
        if not params:
            params = ["void"]
        if len(rets) == 0:
            ret = "void"
        elif len(rets) == 1:
            ret = ctype_of(rets[0])
        else:
            ret = "void"  # multi-return uses out-params
        return f"{ret} veloce_{fn.name}({', '.join(params)})"

    def declare_weights(self, fn):
        # Any tensor param that is a trit/fp16 weight gets a storage-typed
        # pointer; other tensors are float pointers. This is already in the
        # signature, so nothing extra to emit here except arena sizes.
        plan = self.plans.get(fn.name)
        if plan is not None:
            self.emit(f"/* {fn.name}: arena peak {plan.report()['peak_bytes']} bytes, "
                      f"reuse saves {plan.report()['reuse_savings_pct']}% */")

    # ---- functions ------------------------------------------------------
    def gen_function(self, fn):
        self.fn = fn
        plan = self.plans.get(fn.name)
        arena_words = getattr(fn, "arena_words", 1)
        self.emit(self.signature(fn) + " {")
        self.indent += 1
        # static arena (zero runtime allocation; lives in BSS). Emit only when
        # the function actually materialises tensors, to avoid empty arrays.
        if plan is not None and plan.peak_words > 0:
            self.emit(f"static float __arena[{arena_words}] __attribute__((aligned(64)));")
        for stmt in fn.body:
            self.gen_stmt(stmt)
        # implicit return
        if not fn.ret_types:
            self.emit("return;")
        self.indent -= 1
        self.emit("}")
        self.emit("")

    # ---- statements -----------------------------------------------------
    def gen_stmt(self, s):
        if isinstance(s, ast.LetStmt):
            self.gen_let(s)
        elif isinstance(s, ast.AssignStmt):
            self.gen_assign(s)
        elif isinstance(s, ast.ReturnStmt):
            self.gen_return(s)
        elif isinstance(s, ast.IfStmt):
            self.gen_if(s)
        elif isinstance(s, ast.WhileStmt):
            self.gen_while(s)
        elif isinstance(s, ast.BreakStmt):
            self.emit("break;")
        elif isinstance(s, ast.ContinueStmt):
            self.emit("continue;")
        elif isinstance(s, ast.ExprStmt):
            t = getattr(s.expr, "ctype", None)
            if is_tensor(t):
                # materialise for side-free semantics; emit as void
                pass
            else:
                self.emit(f"(void)({self.gen_expr(s.expr)});")
        else:
            raise NotImplementedError(type(s).__name__)

    def _sym_ctype(self, sym):
        return ctype_of(sym.type)

    def gen_let(self, s):
        t = getattr(s.expr, "ctype", None)
        if isinstance(t, TupleType):
            # let a, b = fn(...)   -> out-parameters
            call = s.expr
            syms = s.symbols
            for sym, vt in zip(syms, t.items):
                self.emit(f"{ctype_of(vt)} {sym.cname};")
            outargs = ", ".join(f"&{sym.cname}" for sym in syms)
            self.emit(f"{self.gen_call_with_outs(call, outargs)};")
            return
        if is_tensor(t):
            # bind to arena slot
            off = getattr(s.expr, "arena_offset_words", None)
            if off is None:
                off = getattr(s, "arena_offset_words", 0) or 0
            self.gen_tensor_expr_into(s.expr, sym_cname=None,
                                      dest=f"(__arena + {off})",
                                      dest_type=t)
            # alias name to the slot pointer
            sym = s.symbols[0]
            self.emit(f"{ctype_of(t)} {sym.cname} = ({ctype_of(t)})(__arena + {off});")
            return
        # scalar
        sym = s.symbols[0]
        val = self.gen_expr(s.expr)
        self.emit(f"{ctype_of(t)} {sym.cname} = {val};")

    def gen_assign(self, s):
        if len(s.targets) > 1:
            call = s.expr
            outargs = ", ".join(f"&{tgt.symbol.cname}" for tgt in s.targets
                                if isinstance(tgt, ast.Var))
            self.emit(f"{self.gen_call_with_outs(call, outargs)};")
            return
        tgt = s.targets[0]
        if isinstance(tgt, ast.Var):
            self.emit(f"{tgt.symbol.cname} = {self.gen_expr(s.expr)};")
        elif isinstance(tgt, ast.Index):
            self.gen_index_store(tgt, s.expr)
        else:
            raise NotImplementedError("assign target")

    def gen_index_store(self, tgt, rhs):
        bt = getattr(tgt.base, "ctype", None)
        base_ptr = self.gen_expr(tgt.base)
        # A row store (`cache[pos] = vector`) copies a whole row; an element
        # store assigns one scalar.  These used to share one code path, which
        # emitted `(float)(ptr)` for a row store -- a silent miscompile.
        if getattr(tgt, "row_store", False):
            rhs_ptr = self.gen_expr(rhs)
            idx = self.gen_expr(tgt.index)
            cols = bt.dims[1].value
            self.emit(f"veloce_copyf({base_ptr} + ({idx}) * {cols}, {rhs_ptr}, {cols});")
            return
        val = self.gen_expr(rhs)
        cast = "float"
        if getattr(bt, "dtype", None) is not None and bt.dtype.name in ("i32", "i64", "i8", "u8"):
            cast = ctype_of(bt).rstrip(" *")
        if isinstance(tgt.index, ast.TupleExpr):
            idxs = [self.gen_expr(i) for i in tgt.index.items]
            cols = bt.dims[1].value
            self.emit(f"{base_ptr}[({idxs[0]}) * {cols} + ({idxs[1]})] = ({cast})({val});")
        else:
            idx = self.gen_expr(tgt.index)
            if bt.rank == 1:
                self.emit(f"{base_ptr}[{idx}] = ({cast})({val});")
            else:
                cols = bt.dims[1].value
                self.emit(f"{base_ptr}[({idx}) * {cols}] = (float)({val});")

    def gen_return(self, s):
        if len(s.exprs) == 0:
            self.emit("return;")
        elif len(s.exprs) == 1:
            e = s.exprs[0]
            t = getattr(e, "ctype", None)
            if is_tensor(t):
                self.emit(f"return {self.tptr(e)};")
            else:
                self.emit(f"return {self.gen_expr(e)};")
        else:
            for i, e in enumerate(s.exprs):
                t = getattr(e, "ctype", None)
                val = self.tptr(e) if is_tensor(t) else self.gen_expr(e)
                self.emit(f"*__out{i} = {val};")
            self.emit("return;")

    def gen_if(self, s):
        self.emit(f"if ({self.gen_expr(s.cond)}) {{")
        self.indent += 1
        for st in s.then_body:
            self.gen_stmt(st)
        self.indent -= 1
        if s.else_body:
            self.emit("} else {")
            self.indent += 1
            for st in s.else_body:
                self.gen_stmt(st)
            self.indent -= 1
        self.emit("}")

    def gen_while(self, s):
        self.emit(f"while ({self.gen_expr(s.cond)}) {{")
        self.indent += 1
        for st in s.body:
            self.gen_stmt(st)
        self.indent -= 1
        self.emit("}")

    # ---- expressions: scalars ------------------------------------------
    def gen_expr(self, e):
        if isinstance(e, ast.IntLit):
            return str(e.value)
        if isinstance(e, ast.FloatLit):
            return repr(float(e.value))
        if isinstance(e, ast.BoolLit):
            return "true" if e.value else "false"
        if isinstance(e, ast.StrLit):
            return f'"{e.value}"'
        if isinstance(e, ast.Var):
            return e.symbol.cname
        if isinstance(e, ast.UnaryOp):
            if e.op == "!":
                return f"(!({self.gen_expr(e.operand)}))"
            return f"(-({self.gen_expr(e.operand)}))"
        if isinstance(e, ast.BinOp):
            return self.gen_binop_expr(e)
        if isinstance(e, ast.Cast):
            return f"(({ctype_of(e.dtype)})({self.gen_expr(e.expr)}))"
        if isinstance(e, ast.Index):
            return self.gen_index_load(e)
        if isinstance(e, ast.Call):
            return self.gen_call_expr(e)
        raise NotImplementedError(type(e).__name__)

    def gen_binop_expr(self, e):
        lt = getattr(e.left, "ctype", None)
        rt = getattr(e.right, "ctype", None)
        if is_tensor(getattr(e, "ctype", None)) or is_tensor(lt) or is_tensor(rt):
            # tensor-valued binary op -> returns a pointer; handled by caller
            raise NotImplementedError("tensor binop in scalar context")
        op = e.op
        if op == "//":
            return f"((int)({self.gen_expr(e.left)}) / (int)({self.gen_expr(e.right)}))"
        return f"({self.gen_expr(e.left)} {op} {self.gen_expr(e.right)})"

    def gen_index_load(self, e):
        bt = getattr(e.base, "ctype", None)
        ptr = self.gen_expr(e.base)
        if getattr(e, "lower", None) == "index2":
            idxs = [self.gen_expr(i) for i in e.index.items]
            cols = bt.dims[1].value
            return f"{ptr}[({idxs[0]}) * {cols} + ({idxs[1]})]"
        if getattr(e, "lower", None) == "indexrow":
            idx = self.gen_expr(e.index)
            cols = bt.dims[1].value
            return f"({ptr} + ({idx}) * {cols})"
        idx = self.gen_expr(e.index)
        return f"{ptr}[{idx}]"

    # ---- expressions: calls (scalar vs tensor) -------------------------
    def gen_call_expr(self, e):
        t = getattr(e, "ctype", None)
        if is_tensor(t):
            raise NotImplementedError("tensor call in scalar context")
        lower = getattr(e, "lower", None)
        if lower in ("exp", "sqrt"):
            return f"{'expf' if lower == 'exp' else 'sqrtf'}({self.gen_expr(e.args[0])})"
        if e.func in self.sigs_names():
            return self.gen_call_multiret(e, as_expr=True)
        if e.func == "argmax":
            ptr = self.gen_expr(e.args[0])
            n = numel(getattr(e.args[0], "ctype"))
            return f"veloce_argmax({ptr}, {n})"
        if e.func == "zeros":
            raise NotImplementedError("zeros in scalar context")
        return self.gen_call_multiret(e, as_expr=True)

    def sigs_names(self):
        return set(f.name for f in self.module.functions)

    # ---- function calls -------------------------------------------------
    def _arg_exprs(self, e):
        out = []
        for a in e.args:
            t = getattr(a, "ctype", None)
            out.append(self.tptr(a) if is_tensor(t) else self.gen_expr(a))
        return out

    def gen_call_multiret(self, e, as_expr=False):
        fname = "veloce_" + e.func
        args = ", ".join(self._arg_exprs(e))
        return f"{fname}({args})"

    def gen_call_with_outs(self, e, outargs):
        fname = "veloce_" + e.func
        args = self._arg_exprs(e)
        args.append(outargs)
        return f"{fname}({', '.join(args)})"

    # ---- tensor expressions --------------------------------------------
    def gen_tensor_expr_into(self, e, sym_cname, dest, dest_type):
        """Materialise tensor-valued expression ``e`` into ``dest`` pointer."""
        if isinstance(e, ast.Call):
            self.gen_tensor_call_into(e, dest)
        elif isinstance(e, ast.BinOp):
            self.gen_tensor_binop_into(e, dest)
        elif isinstance(e, ast.Var):
            # pointer copy
            src = e.symbol.cname
            n = numel(dest_type)
            self.emit(f"veloce_copyf({dest}, {src}, {n});")
        elif isinstance(e, ast.Index):
            # row view -> copy row
            src = self.tptr(e)
            n = numel(dest_type)
            self.emit(f"veloce_copyf({dest}, {src}, {n});")
        elif isinstance(e, ast.Cast):
            self.gen_tensor_expr_into(e.expr, None, dest, dest_type)
        else:
            raise NotImplementedError(f"tensor expr {type(e).__name__}")

    def _dst(self, e):
        off = getattr(e, "arena_offset_words", 0)
        return f"(__arena + {off})"

    def tptr(self, e):
        """Return a C pointer expression for a tensor-valued expression,
        materialising nested temporaries into their arena slots first."""
        if isinstance(e, ast.Var):
            return e.symbol.cname
        if isinstance(e, ast.Index) and getattr(e, "lower", None) == "indexrow":
            return self.gen_index_load(e)
        if isinstance(e, ast.Cast):
            return self.tptr(e.expr)
        # tensor Call / BinOp / row Index: materialise into owned slot
        self.gen_tensor_expr_into(e, None, self._dst(e), e.ctype)
        return self._dst(e)

    def gen_tensor_call_into(self, e, dest):
        d = dest or self._dst(e)
        out = getattr(e, "ctype")
        lower = getattr(e, "lower", None)
        if lower is None and e.func in self.sigs_names():
            # user-defined function returning a tensor: copy its arena result
            call = self.gen_call_multiret(e)
            n = numel(out)
            self.emit(f"veloce_copyf({d}, {call}, {n});")
            return
        if lower == "matmul_f32":
            x = self.tptr(e.args[0])
            w = self.tptr(e.args[1])
            lt = getattr(e.args[0], "ctype")
            rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[1].value
            if rt.dtype.name == "fp16":
                self.emit(f"veloce_matmul_f16w({d}, {x}, {w}, {M}, {K}, {N});")
            else:
                self.emit(f"veloce_matmul_f32({d}, {x}, {w}, {M}, {K}, {N});")
        elif lower == "matmul_i4":
            d = dest or self._dst(e)
            x = self.tptr(e.args[0])
            w = self.tptr(e.args[1])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_i4({d}, {x}, {w}, {M}, {K}, {N});")
        elif lower in ("matmul_i4g", "matmul_i2g", "matmul_fp8g"):
            # One code path for the three group-scaled kernels: identical
            # contract, only the weight dtype and the runtime symbol differ.
            d = dest or self._dst(e)
            x = self.tptr(e.args[0]); w = self.tptr(e.args[1]); sc = self.tptr(e.args[2])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            st = getattr(e.args[2], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            # The caller declares scales as [N, n_groups] and the runtime takes
            # the group SIZE, deriving n_groups back as K / G.  The two only
            # agree when the group count divides K exactly, which typecheck
            # enforces; with that guaranteed, K // n_groups is exact.  (This
            # used to be a bare floor division, which silently mismatched the
            # runtime for ragged shapes such as K=100 over 7 groups and scaled
            # every row against the wrong slices.)
            ngroups = st.dims[1].value
            G = K // ngroups
            self.emit(f"veloce_{lower}({d}, {x}, {w}, {sc}, {M}, {K}, {N}, {G});")
        elif lower == "matmul_i2":
            d = dest or self._dst(e)
            x = self.tptr(e.args[0]); w = self.tptr(e.args[1])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_i2({d}, {x}, {w}, {M}, {K}, {N});")
        elif lower == "matmul_i2_s":
            d = dest or self._dst(e)
            x = self.tptr(e.args[0]); w = self.tptr(e.args[1]); sc = self.tptr(e.args[2])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_i2_s({d}, {x}, {w}, {sc}, {M}, {K}, {N});")
        elif lower == "matmul_fp8":
            d = dest or self._dst(e)
            x = self.tptr(e.args[0]); w = self.tptr(e.args[1])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_fp8({d}, {x}, {w}, {M}, {K}, {N});")
        elif lower == "matmul_fp8_s":
            d = dest or self._dst(e)
            x = self.tptr(e.args[0]); w = self.tptr(e.args[1]); sc = self.tptr(e.args[2])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_fp8_s({d}, {x}, {w}, {sc}, {M}, {K}, {N});")
        elif lower == "matmul_trit_s":
            d = dest or self._dst(e)
            x = self.tptr(e.args[0]); w = self.tptr(e.args[1]); sc = self.tptr(e.args[2])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_trit_s({d}, {x}, {w}, {sc}, {M}, {K}, {N});")
            self.diag.setdefault("trit_kernels", 0)
            self.diag["trit_kernels"] += 1
        elif lower == "matmul_f16wt":
            d = dest or self._dst(e)
            x = self.tptr(e.args[0]); w = self.tptr(e.args[1])
            lt = getattr(e.args[0], "ctype"); rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_f16wt({d}, {x}, {w}, {M}, {K}, {N});")
        elif lower == "matmul_trit":
            x = self.tptr(e.args[0])
            w = self.tptr(e.args[1])
            lt = getattr(e.args[0], "ctype")
            rt = getattr(e.args[1], "ctype")
            M, K = lt.dims[0].value, lt.dims[1].value
            N = rt.dims[0].value
            self.emit(f"veloce_matmul_trit({d}, {x}, {w}, {M}, {K}, {N});")
            self.diag.setdefault("trit_kernels", 0)
            self.diag["trit_kernels"] += 1
        elif lower == "rmsnorm":
            x = self.tptr(e.args[0])
            w = self.tptr(e.args[1])
            t = getattr(e.args[0], "ctype")
            n = numel(t)
            wt = getattr(e.args[1], "ctype")
            fn = "veloce_rmsnorm_h" if wt.dtype.name == "fp16" else "veloce_rmsnorm"
            self.emit(f"{fn}({d}, {x}, {w}, {n}, {t.dims[-1].value});")
        elif lower == "silu":
            x = self.tptr(e.args[0])
            n = numel(getattr(e.args[0], "ctype"))
            self.emit(f"veloce_silu({d}, {x}, {n});")
        elif lower == "relu":
            x = self.tptr(e.args[0])
            n = numel(getattr(e.args[0], "ctype"))
            self.emit(f"veloce_relu({d}, {x}, {n});")
        elif lower == "softmax":
            x = self.tptr(e.args[0])
            t = getattr(e.args[0], "ctype")
            n = numel(t)
            self.emit(f"veloce_softmax({d}, {x}, {n}, {t.dims[-1].value});")
        elif lower == "softmax_mask":
            x = self.tptr(e.args[0])
            m = self.tptr(e.args[1])
            t = getattr(e.args[0], "ctype")
            mt = getattr(e.args[1], "ctype")
            n = numel(t)
            # Rank picks the kernel: a 1-D mask is broadcast to every row, a
            # 2-D mask supplies one row per scores row (per-head causal).
            # Emitting the broadcast kernel for a 2-D mask would quietly use
            # mask row 0 for every row, so the choice is not cosmetic.
            fn = ("veloce_softmax_masked_rows" if mt.rank == 2
                  else "veloce_softmax_masked")
            self.emit(f"{fn}({d}, {x}, {m}, {n}, {t.dims[-1].value});")
        elif lower == "transpose":
            x = self.tptr(e.args[0])
            t = getattr(e.args[0], "ctype")
            R, C = t.dims[0].value, t.dims[1].value
            self.emit(f"veloce_transpose({d}, {x}, {R}, {C});")
        elif lower == "rope":
            x = self.tptr(e.args[0])
            t = getattr(e.args[0], "ctype")
            self.emit(f"veloce_rope({d}, {x}, {t.dims[0].value}, {t.dims[1].value});")
        elif lower == "rope_heads":
            x = self.tptr(e.args[0])
            pos = self.gen_expr(e.args[1])
            t = getattr(e.args[0], "ctype")
            self.emit(f"veloce_rope_heads({d}, {x}, {t.dims[0].value}, "
                      f"{t.dims[1].value}, {e.n_heads}, {pos}, {e.theta}f);")
        elif lower == "embedding":
            table = self.tptr(e.args[0])
            idx = self.gen_expr(e.args[1])
            tt = getattr(e.args[0], "ctype")
            fn = "veloce_embedding_h" if tt.dtype.name == "fp16" else "veloce_embedding"
            self.emit(f"{fn}({d}, {table}, {idx}, {tt.dims[1].value});")
        elif lower == "embedding_seq":
            table = self.tptr(e.args[0])
            ids = self.tptr(e.args[1])
            tt = getattr(e.args[0], "ctype")
            it = getattr(e.args[1], "ctype")
            fn = "veloce_embedding_seq_h" if tt.dtype.name == "fp16" else "veloce_embedding_seq"
            self.emit(f"{fn}({d}, {table}, {ids}, "
                      f"{it.dims[0].value}, {tt.dims[1].value});")
        elif lower == "meanpool":
            x = self.tptr(e.args[0])
            t = getattr(e.args[0], "ctype")
            self.emit(f"veloce_meanpool({d}, {x}, {t.dims[0].value}, {t.dims[1].value});")
        elif lower == "zeros":
            n = numel(out)
            if getattr(out, "dtype", None) is not None and out.dtype.name in ("i32", "i64", "i8", "u8"):
                ct = ctype_of(out).rstrip(" *")
                self.emit(f"memset({d}, 0, {n} * sizeof({ct}));")
            else:
                self.emit(f"veloce_zerof({d}, {n});")
        else:
            raise NotImplementedError(f"tensor call lower={lower}")

    def gen_tensor_binop_into(self, e, dest):
        d = dest or self._dst(e)
        lt = getattr(e.left, "ctype")
        rt = getattr(e.right, "ctype")
        # --- operator fusion (FR-2.2): collapse a pure elementwise chain into a
        # single register-resident loop, eliminating intermediate buffers.
        if not getattr(e, "bcast", None) and self._is_pure_ew(e):
            expr = self._build_ew(e, "i")
            n = numel(e.ctype)
            self.emit(f"for (size_t i = 0; i < {n}; i++) {d}[i] = {expr};")
            self.diag["fused_loops"] = self.diag.get("fused_loops", 0) + 1
            return
        bcast = getattr(e, "bcast", None)
        if bcast is not None and is_tensor(lt) and is_tensor(rt):
            cols = bcast[1]
            rows = numel(getattr(e, "ctype")) // cols
            opn = {"+": "add", "-": "sub", "*": "mul", "/": "div"}[e.op]
            a = self.tptr(e.left); b = self.tptr(e.right)
            if bcast[0] == "right":
                self.emit(f"veloce_row{opn}({d}, {a}, {b}, {cols}, {rows});")
            else:
                self.emit(f"veloce_lrow{opn}({d}, {a}, {b}, {cols}, {rows});")
            return
        # elementwise / broadcast
        if is_tensor(lt) and is_tensor(rt):
            a = self.tptr(e.left)
            b = self.tptr(e.right)
            n = numel(getattr(e, "ctype"))
            fn = self._binop_fn(e.op)
            self.emit(f"{fn}({d}, {a}, {b}, {n});")
        elif is_tensor(lt) and not is_tensor(rt):
            a = self.tptr(e.left)
            b = self.gen_expr(e.right)
            n = numel(getattr(e, "ctype"))
            fn = self._scalar_binop_fn(e.op)
            self.emit(f"{fn}({d}, {a}, (float)({b}), {n});")
        elif not is_tensor(lt) and is_tensor(rt):
            a = self.gen_expr(e.left)
            b = self.tptr(e.right)
            n = numel(getattr(e, "ctype"))
            fn = self._scalar_binop_fn(e.op, scalar_left=True)
            self.emit(f"{fn}({d}, {b}, (float)({a}), {n});")
        else:
            raise NotImplementedError("scalar binop routed as tensor")

    def _binop_fn(self, op):
        return {
            "+": "veloce_add", "-": "veloce_sub", "*": "veloce_mul", "/": "veloce_div",
        }[op]

    # -- elementwise fusion helpers --------------------------------------
    def _is_pure_ew(self, e):
        """True if `e` is a same-shape elementwise chain we can fuse into one
        loop: tensor operands are leaves (vars, index-rows, tensor calls) or
        nested fusable ops; no broadcasting, matmul, or comparisons."""
        if not is_tensor(getattr(e, "ctype", None)):
            return False
        if isinstance(e, ast.Var):
            return True
        if isinstance(e, ast.Index):
            return getattr(e, "lower", None) == "indexrow"
        if isinstance(e, ast.Call):
            # tensor-valued call (rmsnorm/silu/... or user fn) as a leaf
            return is_tensor(getattr(e, "ctype", None))
        if isinstance(e, ast.Cast):
            return self._is_pure_ew(e.expr)
        if isinstance(e, ast.UnaryOp):
            return e.op == "-" and self._is_pure_ew(e.operand)
        if isinstance(e, ast.BinOp):
            if e.op not in ("+", "-", "*", "/"):
                return False
            if getattr(e, "bcast", None):
                return False
            lt, rt = getattr(e.left, "ctype", None), getattr(e.right, "ctype", None)
            lt_t, rt_t = is_tensor(lt), is_tensor(rt)
            if lt_t and rt_t:
                if numel(lt) != numel(rt):
                    return False
                return self._is_pure_ew(e.left) and self._is_pure_ew(e.right)
            # tensor-scalar (uniform): fusable if the tensor side is fusable
            if lt_t and not rt_t:
                return self._is_pure_ew(e.left)
            if rt_t and not lt_t:
                return self._is_pure_ew(e.right)
        return False

    def _build_ew(self, e, i):
        """Build a C scalar expression for one lane index `i` of a pure
        elementwise chain.  Leaves are pre-materialised into their arena slots
        and addressed by [i]."""
        if isinstance(e, ast.Var):
            return f"{e.symbol.cname}[{i}]"
        if isinstance(e, ast.Index) and getattr(e, "lower", None) == "indexrow":
            return f"{self.tptr(e)}[{i}]"
        if isinstance(e, ast.Call):
            return f"{self.tptr(e)}[{i}]"
        if isinstance(e, ast.Cast):
            return f"((float)({self._build_ew(e.expr, i)}))"
        if isinstance(e, ast.UnaryOp):
            return f"(-({self._build_ew(e.operand, i)}))"
        if isinstance(e, ast.BinOp):
            lt, rt = getattr(e.left, "ctype", None), getattr(e.right, "ctype", None)
            lhs = self._build_ew(e.left, i) if is_tensor(lt) else self.gen_expr(e.left)
            rhs = self._build_ew(e.right, i) if is_tensor(rt) else self.gen_expr(e.right)
            if not is_tensor(lt):
                lhs = f"(float)({lhs})"
            if not is_tensor(rt):
                rhs = f"(float)({rhs})"
            return f"({lhs} {e.op} {rhs})"
        raise NotImplementedError(type(e).__name__)

    def _bcast_fn(self, op, side):
        base = {"+": "add", "-": "sub", "*": "mul", "/": "div"}[op]
        if side == "right":
            return f"veloce_row{base}"
        else:  # bias on the left: b (op) a
            if op in ("+", "*"):
                return f"veloce_row{base}"  # commutative, reuse right-broadcast
            return f"veloce_row_r{base}"

    def _scalar_binop_fn(self, op, scalar_left=False):
        m = {"+": "add", "-": "sub", "*": "mul", "/": "div"}
        if op == "-" and scalar_left:
            return "veloce_rsub"
        return "veloce_s" + m[op]
