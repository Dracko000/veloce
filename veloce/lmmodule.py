"""Veloce source generation for a decoder-shaped module.

The end-to-end benchmark needs the *same* network at more than one size
(275M trits at d_model=1536, a 0.5B-shaped variant at d_model=2048).  Hand
maintaining one ``.vel`` file per shape is how ``examples/midi_lm_05b.vel``
came to exist as an untracked orphan that no test or Makefile target could
produce.  This module renders the module text from a config dict, so one
command can build either shape, and the checked-in ``examples/midi_lm.vel``
is the rendering for the default config (``test_midi_lm_module_in_sync``
fails if the two ever drift).

The rendered module is deliberately trivial to reason about:

* no ``for`` loops, everything is a tensor expression,
* every weight is a parameter, so the host decides where it lives (mmap),
* ``forward`` is a fixed unrolled chain of ``layer`` calls: the DSL has no
  loops or recursion, so the layer count is baked into the signature.

Config keys: ``V`` (vocab), ``D`` (d_model), ``F`` (ffn), ``layers``,
``name`` (module name) and optionally ``scale`` (attention scale; defaults to
``1/sqrt(D)``, the standard transformer choice).
"""
import math

DEFAULT_CONFIG = dict(name="midi_lm", V=32000, D=1536, F=6144, layers=6)

# Layer weight order in `layer()` and in `forward()`'s parameter list.
LAYER_MATS = (("wq", "trit[D, D]"), ("wk", "trit[D, D]"), ("wv", "trit[D, D]"),
              ("wo", "trit[D, D]"), ("w1", "trit[F, D]"), ("w2", "trit[D, F]"),
              ("w3", "trit[F, D]"))


def attn_scale(cfg):
    """Attention scale: `1/sqrt(d_model)` unless the cfg overrides it."""
    if cfg.get("scale"):
        return float(cfg["scale"])
    return 1.0 / math.sqrt(cfg["D"])


def normalize_config(cfg):
    """Fill in defaults and validate, returning a new dict."""
    out = dict(DEFAULT_CONFIG)
    out.update({k: cfg[k] for k in ("name", "V", "D", "F", "layers") if k in cfg})
    if "scale" in cfg:
        out["scale"] = float(cfg["scale"])
    for k in ("V", "D", "F", "layers"):
        if int(out[k]) <= 0:
            raise ValueError(f"config key {k} must be positive, got {out[k]!r}")
        out[k] = int(out[k])
    return out


def param_names(cfg):
    """Weight names in `forward` order (host offsets are keyed by these)."""
    cfg = normalize_config(cfg)
    names = ["emb"]
    for l in range(1, cfg["layers"] + 1):
        names.append(f"nw{l}")
        names.extend(f"{n}{l}" for n, _ in LAYER_MATS)
    names.extend(["nwf", "head"])
    return names


def decoder_module(cfg):
    """Render Veloce source for the decoder described by `cfg`."""
    cfg = normalize_config(cfg)
    V, D, F, L = cfg["V"], cfg["D"], cfg["F"], cfg["layers"]

    out = [f"""\
# Generated by veloce/lmmodule.py -- do not edit by hand.
# Regenerate with: make model-module   (V={V} D={D} F={F} layers={L})
module {cfg['name']}

dim V = {V}
dim D = {D}
dim F = {F}

fn attn(q: f32[1, D], k: f32[1, D], v: f32[1, D]) -> f32[1, D] {{
    let kt = transpose(k)
    let scores = matmul(q, kt)
    let probs = softmax(scores * {attn_scale(cfg):.9g})
    return matmul(probs, v)
}}

fn layer(x: f32[1, D], nw: f32[D],
         wq: trit[D, D], wk: trit[D, D], wv: trit[D, D], wo: trit[D, D],
         w1: trit[F, D], w2: trit[D, F], w3: trit[F, D]) -> f32[1, D] {{
    let xn = rmsnorm(x, nw)
    let q = matmul_trit(xn, wq)
    let k = matmul_trit(xn, wk)
    let v = matmul_trit(xn, wv)
    let a = attn(q, k, v)
    let o = matmul_trit(a, wo)
    let x1 = x + o
    let xn2 = rmsnorm(x1, nw)
    let g = matmul_trit(xn2, w1)
    let u = matmul_trit(xn2, w3)
    let h = silu(g) * u
    let d = matmul_trit(h, w2)
    return x1 + d
}}

fn forward(
    emb: fp16[V, D],
    tok: i32,"""]
    for l in range(1, L + 1):
        out.append(f"    nw{l}: f32[D],")
        for name, shape in LAYER_MATS:
            out.append(f"    {name}{l}: {shape},")
    out.append("    nwf: f32[D],")
    out.append("    head: trit[V, D]) -> f32[1, V] {")
    out.append("    let x0 = embedding(emb, tok)")
    for l in range(1, L + 1):
        prev = "x0" if l == 1 else f"x{l - 1}"
        args = ", ".join([prev] + [f"{n}{l}" for n in
                                  ("nw",) + tuple(n for n, _ in LAYER_MATS)])
        out.append(f"    let x{l} = layer({args})")
    out.append(f"    let xn = rmsnorm(x{L}, nwf)")
    out.append("    return matmul_trit(xn, head)")
    out.append("}")
    return "\n".join(out) + "\n"
